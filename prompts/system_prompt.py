def get_gene_adjustment_prompt(gene_variants: dict) -> str:
    """基于基因变异生成调整建议提示"""
    adjustments = []

    if "MTHFR" in gene_variants:
        adjustments.append("检测到MTHFR基因变异，推荐使用活性叶酸（L-5-MTHF）而非普通叶酸")

    if "VDR" in gene_variants:
        adjustments.append("检测到VDR基因变异，可能需要更高剂量的维生素D3（3000-5000 IU）")

    if "FADS1" in gene_variants or "FADS2" in gene_variants:
        adjustments.append("检测到FADS基因变异，直接补充EPA+DHA而非依赖体内转化")

    if "HFE" in gene_variants:
        adjustments.append("检测到HFE基因变异（血色病风险），避免补充铁剂")

    if "COMT" in gene_variants:
        adjustments.append("检测到COMT基因变异（压力敏感），建议增加压力管理和镁摄入")

    if "BDNF" in gene_variants:
        adjustments.append("检测到BDNF基因变异，建议关注Omega-3和认知营养素")

    return "\n".join(adjustments) if adjustments else ""
